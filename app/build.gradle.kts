// Local properties take precedence; CI supplies environment variables instead.
// With neither configured, release artifacts are unsigned for F-Droid builders.
val releaseSigning: Map<String, String>? =
    run {
        val fromFile =
            rootProject.file("keystore.properties").takeIf { it.exists() }?.let { file ->
                val props = Properties().apply { file.inputStream().use(::load) }
                listOf("storeFile", "storePassword", "keyAlias", "keyPassword")
                    .associateWith { props.getProperty(it) }
            }
        val fromEnv =
            mapOf(
                "storeFile" to "DRUMS_KEYSTORE_FILE",
                "storePassword" to "DRUMS_KEYSTORE_PASSWORD",
                "keyAlias" to "DRUMS_KEY_ALIAS",
                "keyPassword" to "DRUMS_KEY_PASSWORD",
            ).mapValues { (_, name) -> providers.environmentVariable(name).orNull }

        listOfNotNull(fromFile, fromEnv)
            .firstOrNull { material -> material.values.none { it.isNullOrBlank() } }
            ?.mapValues { (_, value) -> value!! }
    }

// Beta signing is independent of release signing; local checks use the debug key.
val betaSigning: Map<String, String>? =
    mapOf(
        "storeFile" to "DRUMS_BETA_KEYSTORE_FILE",
        "storePassword" to "DRUMS_BETA_KEYSTORE_PASSWORD",
        "keyAlias" to "DRUMS_BETA_KEY_ALIAS",
        "keyPassword" to "DRUMS_BETA_KEY_PASSWORD",
    ).mapValues { (_, name) -> providers.environmentVariable(name).orNull }
        .takeIf { material -> material.values.none { it.isNullOrBlank() } }
        ?.mapValues { (_, value) -> value!! }

val betaVersionCode = providers.environmentVariable("DRUMS_BETA_VERSION_CODE").orNull?.toInt()
val betaVersionName = providers.environmentVariable("DRUMS_BETA_VERSION_NAME").orNull

